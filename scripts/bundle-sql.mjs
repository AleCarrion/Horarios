// Joins every migration and the seed into supabase/setup_all.sql: one paste in the Supabase SQL editor sets a new project up.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "supabase");
export const bundle = () => {
  const parts = readdirSync(join(root, "migrations")).filter((f) => f.endsWith(".sql")).sort().map((f) => `-- ===== migrations/${f} =====\n${readFileSync(join(root, "migrations", f), "utf8").trim()}\n`);
  parts.push(`-- ===== seed.sql =====\n${readFileSync(join(root, "seed.sql"), "utf8").trim()}\n`);
  return `-- GENERATED by scripts/bundle-sql.mjs (npm run db:bundle). Do not edit by hand.\n-- Paste the whole file in the Supabase SQL editor on a NEW project. Not for projects that already ran some migrations.\n\n${parts.join("\n")}`;
};
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, "setup_all.sql"), bundle());
  console.log("supabase/setup_all.sql written");
}
